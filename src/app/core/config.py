from pathlib import Path
import sys

# ==============================================================
#                    ДЕФОЛТНЫЕ НАСТРОЙКИ
# ==============================================================
# Меняй значения здесь. При сборке в .exe они вшиваются в программу.
# Больше не нужно создавать config.ini и передавать его через --add-data.
DEFAULTS = {
    "App": {
        "log_level": "INFO",
    },
    # Сюда можно добавлять другие секции в будущем, например:
    # "UI": {
    #     "theme": "dark",
    # }
}


# ==============================================================
#                    БАЗОВАЯ ДИРЕКТОРИЯ
# ==============================================================
# Определяем базовую директорию с учётом PyInstaller.
# Нужна для правильного сохранения логов и поиска ресурсов.
if getattr(sys, "frozen", False):
    # Если это скомпилированный .exe, папка рядом с ним
    BASE_DIR = Path(sys.executable).resolve().parent
else:
    # Если запускаем из исходников, поднимаемся до корня проекта
    BASE_DIR = Path(__file__).resolve().parents[2]


# ==============================================================
#                    ПУБЛИЧНЫЕ КОНСТАНТЫ
# ==============================================================
# Достаем настройки из словаря.
# .get() безопасно вернет значение по умолчанию, если ключа нет.
LOG_LEVEL = DEFAULTS.get("App", {}).get("log_level", "INFO")
